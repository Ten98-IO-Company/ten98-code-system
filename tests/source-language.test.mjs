import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { inspectSourcePolicy, omittedRoots } from '../check.mjs';

function fixture(run) {
  const root = mkdtempSync(join(tmpdir(), 'ten98-source-'));
  try {
    mkdirSync(join(root, 'src'));
    writeFileSync(join(root, 'src/main.ts'), 'export const amount: number = 1;');
    const policy = { default: 'typescript', roots: ['src'], legacyJavaScript: [], generated: {} };
    const program = { compilerOptions: { strict: true }, files: ['src/main.ts'] };
    run(root, policy, program);
  } finally { rmSync(root, { recursive: true, force: true }); }
}

test('source policy admits checked TypeScript and only exact legacy JavaScript paths', () => fixture((root, policy, program) => {
  assert.deepEqual(inspectSourcePolicy(root, policy, program), []);
  writeFileSync(join(root, 'src/retained.mjs'), 'export const retained = true;');
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /new authored JavaScript/);
  policy.legacyJavaScript = ['src/retained.mjs'];
  assert.deepEqual(inspectSourcePolicy(root, policy, program), []);
  writeFileSync(join(root, 'src/second.js'), 'export const second = true;');
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /src\/second.js/);
}));

test('source policy rejects omitted TypeScript and missing production roots', () => fixture((root, policy, program) => {
  program.files = [];
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /absent from the configured compiler/);
  policy.roots.push('server');
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /Required source root missing: server/);
}));

test('new production code cannot escape through an undeclared folder or broad native-script exception', () => fixture((root, policy, program) => {
  mkdirSync(join(root, 'api'));
  writeFileSync(join(root, 'api/unchecked.mjs'), 'export const unchecked = true;');
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /api\/unchecked.mjs: code outside/);
  policy.nativeFiles = { 'scripts/existing.mjs': 'Reviewed native runner' };
  mkdirSync(join(root, 'scripts'));
  writeFileSync(join(root, 'scripts/existing.mjs'), 'export const runner = true;');
  writeFileSync(join(root, 'scripts/new.mjs'), 'export const hidden = true;');
  const errors = inspectSourcePolicy(root, policy, program).join('\n');
  assert.doesNotMatch(errors, /scripts\/existing.mjs/);
  assert.match(errors, /scripts\/new.mjs: code outside/);
}));

test('source policy rejects disabled semantic checking and strict option overrides', () => fixture((root, policy, program) => {
  for (const name of ['strict', 'noImplicitAny', 'noImplicitThis', 'strictNullChecks', 'strictFunctionTypes', 'strictBindCallApply', 'strictPropertyInitialization', 'strictBuiltinIteratorReturn', 'alwaysStrict', 'useUnknownInCatchVariables']) {
    program.compilerOptions = { strict: true, [name]: false };
    assert.match(inspectSourcePolicy(root, policy, program).join('\n'), new RegExp(name));
  }
  program.compilerOptions = { strict: true, noCheck: true };
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /noCheck/);
  program.projects = [{ compilerOptions: { strict: true } }, { compilerOptions: { strict: true, noCheck: true } }];
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /noCheck/);
  program.projects[1].compilerOptions = { strict: false };
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /strict/);
}));

test('source policy rejects authored nocheck; generated exceptions require exact path and provenance', () => fixture((root, policy, program) => {
  writeFileSync(join(root, 'src/main.ts'), '// @ts-nocheck\nexport const amount: number = "wrong";');
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /@ts-nocheck/);
  policy.generated['src/routeTree.gen.ts'] = 'Generated by the route generator.';
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /src\/main.ts/);
  writeFileSync(join(root, 'src/main.ts'), 'export const amount = 1;');
  writeFileSync(join(root, 'src/routeTree.gen.ts'), '// @ts-nocheck\n');
  program.files.push('src/routeTree.gen.ts');
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /provenance marker is missing/);
  writeFileSync(join(root, 'src/routeTree.gen.ts'), '// Generated by the route generator.\n// @ts-nocheck\n');
  assert.deepEqual(inspectSourcePolicy(root, policy, program), []);
}));

test('legacy JavaScript entries go stale once their file is removed, moved out of a root or into an artifact directory', () => fixture((root, policy, program) => {
  policy.legacyJavaScript = ['src/removed.mjs'];
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /src\/removed.mjs: stale legacyJavaScript/);
  mkdirSync(join(root, 'tools'));
  writeFileSync(join(root, 'tools/moved.mjs'), 'export const moved = true;');
  policy.nativeFiles = { 'tools/moved.mjs': 'Reviewed native runner' };
  policy.legacyJavaScript = ['tools/moved.mjs'];
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /tools\/moved.mjs: stale legacyJavaScript/);
  mkdirSync(join(root, 'src/fixtures'));
  writeFileSync(join(root, 'src/fixtures/input.mjs'), 'export const input = true;');
  policy.legacyJavaScript = ['src/fixtures/input.mjs'];
  assert.deepEqual(inspectSourcePolicy(root, policy, program), []);
  policy.artifactDirectories = ['src/fixtures'];
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /src\/fixtures\/input.mjs: stale legacyJavaScript/);
}));

test('nested artifact directories under a source root hold checker inputs, not authored source', () => fixture((root, policy, program) => {
  policy.roots.push('tests');
  mkdirSync(join(root, 'tests/fixtures'), { recursive: true });
  writeFileSync(join(root, 'tests/fixtures/page.tsx'), 'export const Page = () => null;');
  writeFileSync(join(root, 'tests/fixtures/payload.mjs'), 'export default {};');
  const errors = inspectSourcePolicy(root, policy, program).join('\n');
  assert.match(errors, /tests\/fixtures\/page.tsx: TypeScript is absent/);
  assert.match(errors, /tests\/fixtures\/payload.mjs: new authored JavaScript/);
  policy.artifactDirectories = ['tests/fixtures'];
  assert.deepEqual(inspectSourcePolicy(root, policy, program), []);
}));

test('a build context without optional tests/scripts roots skips their ratchet; present roots and production roots stay strict', () => fixture((root, policy, program) => {
  policy.roots.push('tests', 'scripts');
  policy.legacyJavaScript = ['tests/old.test.mjs', 'scripts/build.mjs'];
  // Docker build contexts copy production roots only, so neither optional root exists here.
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /Required source root missing: tests/);
  policy.optionalRoots = ['tests', 'scripts'];
  assert.deepEqual(omittedRoots(root, policy), ['tests', 'scripts']);
  assert.deepEqual(inspectSourcePolicy(root, policy, program), []);
  // Once a root is present, as in repository CI, its stale entries fail again.
  mkdirSync(join(root, 'tests'));
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /tests\/old.test.mjs: stale legacyJavaScript/);
  assert.doesNotMatch(inspectSourcePolicy(root, policy, program).join('\n'), /scripts\/build.mjs/);
  // A production root is never optional.
  policy.roots.push('server');
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /Required source root missing: server/);
}));

test('source roots still catch upper-case JavaScript, unclassified native scripts and file-named artifact entries', () => fixture((root, policy, program) => {
  policy.roots.push('scripts');
  mkdirSync(join(root, 'scripts'));
  writeFileSync(join(root, 'scripts/run.ps1'), 'Write-Output run');
  writeFileSync(join(root, 'scripts/tool.JS'), 'export const tool = true;');
  writeFileSync(join(root, 'scripts/hidden.mjs'), 'export const hidden = true;');
  policy.artifactDirectories = ['scripts/hidden.mjs'];
  const errors = inspectSourcePolicy(root, policy, program).join('\n');
  assert.match(errors, /scripts\/run.ps1: code outside/);
  assert.match(errors, /scripts\/tool.JS: new authored JavaScript/);
  assert.match(errors, /scripts\/hidden.mjs: new authored JavaScript/);
  policy.nativeFiles = { 'scripts/run.ps1': 'Reviewed Windows runner' };
  assert.doesNotMatch(inspectSourcePolicy(root, policy, program).join('\n'), /run.ps1/);
}));

test('compiler projects covering TypeScript tests or scripts require erasableSyntaxOnly', () => fixture((root, policy, program) => {
  policy.roots.push('tests');
  mkdirSync(join(root, 'tests'));
  writeFileSync(join(root, 'tests/types.d.mts'), 'export type Amount = number;');
  program.files.push('tests/types.d.mts');
  assert.deepEqual(inspectSourcePolicy(root, policy, program), []);
  writeFileSync(join(root, 'tests/contract.mts'), 'export const amount: number = 1;');
  program.files.push('tests/contract.mts');
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /tests\/contract.mts: a compiler project covering tests or scripts must enable erasableSyntaxOnly/);
  program.compilerOptions.erasableSyntaxOnly = true;
  assert.deepEqual(inspectSourcePolicy(root, policy, program), []);
  program.projects = [
    { compilerOptions: { strict: true }, files: ['src/main.ts'] },
    { compilerOptions: { strict: true }, files: [join(root, 'tests/contract.mts')] },
  ];
  assert.match(inspectSourcePolicy(root, policy, program).join('\n'), /tests\/contract.mts: .*erasableSyntaxOnly/);
  program.projects[1].compilerOptions.erasableSyntaxOnly = true;
  assert.deepEqual(inspectSourcePolicy(root, policy, program), []);
}));
